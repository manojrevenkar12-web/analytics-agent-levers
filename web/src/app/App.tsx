import { Gate } from "../features/gate/Gate";
import { HeldOut } from "../features/heldout/HeldOut";
import { Hero } from "../features/answers/Hero";
import { Levers } from "../features/levers/Levers";
import { ShipOrder } from "../features/order/ShipOrder";
import type { Data } from "../shared/data/types";
import type { Fetcher } from "../shared/data/useJson";
import { browserFetch, useJson } from "../shared/data/useJson";
import { color, measure, size, space } from "../shared/theme/tokens";
import { Section } from "../shared/ui/Section";
import { EmptyNotice, ErrorNotice, Skeleton } from "../shared/ui/States";

export function App({ fetcher = browserFetch }: { fetcher?: Fetcher }) {
  const load = useJson<Data>("./data.json", fetcher);
  return (
    <main style={{ maxWidth: measure.page, margin: "0 auto", padding: `0 ${space[5]}px ${space[8]}px` }}>
      {load.state === "loading" && <Skeleton />}
      {load.state === "error" && <ErrorNotice message={load.message} onRetry={load.retry} />}
      {load.state === "ready" && <Dashboard data={load.data} />}
    </main>
  );
}

function Dashboard({ data }: { data: Data }) {
  if (!data.summary || !data.summary.baseline || !data.summary.all) {
    return (
      <div style={{ padding: `${space[8]}px 0` }}>
        <EmptyNotice what="evaluation results" command="python scripts/evaluate.py && python scripts/report.py" />
      </div>
    );
  }
  const askLimit = data.gate.all?.checks.find((c) => c.check.startsWith("clarifying"))?.limit ?? 0;
  return (
    <>
      <Hero data={data} />
      <Section id="levers" title="Each lever on its own, and all four" lede="Open a setting to see which kinds of question it gets wrong. Violet marks a setting that asks people back more than the gate allows.">
        <Levers summary={data.summary} data={data} rows={data.order} />
      </Section>
      <Section id="order" title="The order to ship them" lede="What each lever adds when the other three are already on. Descriptions first; 'not sure' pays off only once the agent has context to be sure about.">
        <ShipOrder data={data} />
      </Section>
      <Section id="gate" title="Launch gate" lede={`A lever ships if its 95% interval for right answers is above zero, it adds no confidently wrong answers, it stays within the cost budget and it asks back at most ${askLimit} times in 100.`}>
        <Gate gate={data.gate} data={data} />
      </Section>
      <Section id="heldout" title="A company nobody tuned for" lede="Other data, more ambiguous questions and words the catalogue has never seen. Run once.">
        <HeldOut data={data} />
      </Section>
      <p style={{ color: color.muted, fontSize: size.xs, margin: 0 }}>
        Model prices: {data.model.name}, ${data.model.input_usd_per_mtok} in and ${data.model.output_usd_per_mtok} out per million tokens. Generated by scripts/report.py.
      </p>
    </>
  );
}
